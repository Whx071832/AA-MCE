"""Decision-layer diagnostics for the Onion three-view study (post hoc, no training).

Quantifies the decision-layer mismatch reported in Section 5.1 of the revised
manuscript and the offline cost reported in Sections 3.3 and 5.4.  Everything is derived
from the frozen runs: per-seed predictions are regenerated by inference from the
saved checkpoints of ``optimized_multimodal_tagging_final_v1`` (C1, C2) and
``availability_aware_ensemble_v1`` (RAMT, AttnFusion, EvidFusion) and checked
against the saved seed-averaged test predictions.

Outputs (``<output-root>/experiments/<run-name>/``):

* ``threshold_shift_by_pattern.csv`` -- per-label validation thresholds of every
  pattern-threshold variant, summarised per availability pattern against the
  complete (audio+lyrics+visual) pattern (read from ``pattern_thresholds.csv``);
* ``validation_probability_by_pattern.csv`` -- mean predicted probability of all,
  positive and negative label entries per pattern on the pattern-masked
  validation tracks (MCE, AA-MCE, RAMT, EvidFusion);
* ``decision_loss_decomposition.csv`` -- per condition, the mean over seeds of
  per-seed Macro-F1 with (i) the global validation thresholds, (ii) the
  per-pattern validation thresholds and (iii) per-label thresholds chosen on the
  test labels themselves.  (iii) is an oracle used only as an upper bound;
  ``share = (ii - i) / (iii - i)``;
* ``observed_subset_map.csv`` -- per-seed mAP of MCE and AA-MCE on the fully
  observed and the audio+lyrics test subsets of the complete condition;
* ``selection_timing.json`` -- CPU time of the offline AA-MCE selection
  (weight grid, per-pattern thresholds, per-pattern Platt), plus a check that the
  regenerated selection equals the saved one.
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import torch
from sklearn.metrics import average_precision_score, f1_score

from .aa_core import fast_thresholds, mix, select_pattern_weights
from .advanced_fusion_baselines import build_model as build_recent_model
from .availability_aware_ensemble import PATTERNS, load_component, pattern_index, pattern_name, predict_any
from .common import environment_record, load_config, resolve_device
from .full_feature_ablation import build_model as build_generic_model
from .optimized_multimodal_tagging import CONDITIONS, load_full_features
from .posthoc_calibration import fit_platt
from .robust_multimodal_tagging import build_dataset, intervention, targets

VARIANT_PAIRS = (  # model, global-threshold variant, pattern-threshold variant (names in pattern_thresholds.csv)
    ("MCE", "MCE", "MCE+AAT"),
    ("RAMT", "RAMT", "RAMT+AAT"),
    ("AA-MCE", "AA-MCE", "AA-MCE"),
    ("AttnFusion", "AttnFusion", "AttnFusion+AAT"),
    ("EvidFusion", "EvidFusion", "EvidFusion+AAT"),
)


def run(project_root: Path, output_base: Path, config: dict[str, Any], run_name: str) -> Path:
    settings = dict(config["availability_aware_ensemble"])
    settings["component_run"] = str(project_root / settings["component_run"])
    aa_root = project_root / "outputs" / "experiments" / "availability_aware_ensemble_v1"
    output_root = output_base / "experiments" / run_name
    output_root.mkdir(parents=True, exist_ok=True)
    started = time.perf_counter()
    device = resolve_device(config["runtime"]["device"])
    processed_root = project_root / config["project"]["processed_root"]
    split_frames, labels, _ = build_dataset(processed_root, int(settings["top_labels"]), int(settings["min_train_tag_frequency"]))
    features, availability, reliability = load_full_features(processed_root, split_frames, include_test=True)
    target = {name: targets(frame, len(labels)) for name, frame in split_frames.items()}
    dims = [values.shape[1] for values in features["train"]]
    seeds = [int(value) for value in settings["seeds"]]
    components = [str(value) for value in settings["candidate_components"]]
    locked = {name: float(value) for name, value in zip(settings["locked_components"], settings["locked_weights"], strict=True)}
    recent_settings = dict(settings, modality_dropout=float(settings["new_model_modality_dropout"]))
    batch = int(settings["evaluation_batch_size"])
    pattern_labels = [pattern_name(p) for p in PATTERNS]
    observed_index = PATTERNS.index((1, 1, 1))

    validation_available = availability["validation"]
    eligible = {i: np.flatnonzero((validation_available >= np.asarray(p, dtype=np.float32)).all(axis=1)) for i, p in enumerate(PATTERNS)}
    masked = {i: np.tile(np.asarray(p, dtype=np.float32), (len(validation_available), 1)) for i, p in enumerate(PATTERNS)}
    condition_masks = {c: intervention(c, availability["test"], 20260910 + n) for n, c in enumerate(CONDITIONS)}
    test_patterns = {}
    for condition, mask in condition_masks.items():
        index = pattern_index(mask)
        test_patterns[condition] = np.where(index < 0, observed_index, index)

    saved_weights = pd.read_csv(aa_root / "pattern_weights.csv")
    saved_weights = saved_weights.loc[saved_weights["variant"] == "AA-MCE"].set_index("pattern")
    aa_weights = {i: {n: float(saved_weights.loc[pattern_labels[i], f"w_{n}"]) for n in components} for i in range(len(PATTERNS))}

    # ---- regenerate per-seed predictions (inference only) ----
    validation_preds: dict[int, dict[int, dict[str, np.ndarray]]] = {}
    test_preds: dict[int, dict[str, dict[str, np.ndarray]]] = {}
    for seed in seeds:
        models = {name: load_component(name, seed, dims, len(labels), settings, device) for name in components[:2]}
        for name in ("RAMT", "AttnFusion", "EvidFusion"):
            model = build_generic_model(name, dims, len(labels), settings) if name == "RAMT" else build_recent_model(name, dims, len(labels), recent_settings)
            model.load_state_dict(torch.load(aa_root / "checkpoints" / f"{name}_{seed}.pt", map_location="cpu", weights_only=True))
            models[name] = model.to(device)
        validation_preds[seed] = {
            i: {n: predict_any(m, [v[eligible[i]] for v in features["validation"]], masked[i][eligible[i]], reliability["validation"][eligible[i]], device, batch) for n, m in models.items()}
            for i in range(len(PATTERNS))
        }
        test_preds[seed] = {c: {n: predict_any(m, features["test"], condition_masks[c], reliability["test"], device, batch) for n, m in models.items()} for c in CONDITIONS}
        del models
        if device.type == "cuda":
            torch.cuda.empty_cache()

    def aa_probability(predictions: dict[str, np.ndarray], patterns: np.ndarray) -> np.ndarray:
        out = np.zeros_like(predictions[components[0]])
        for i in np.unique(patterns):
            rows = patterns == i
            out[rows] = mix({k: v[rows] for k, v in predictions.items()}, aa_weights[int(i)])
        return out

    def probability(model: str, predictions: dict[str, np.ndarray], patterns: np.ndarray | None, index: int | None = None) -> np.ndarray:
        if model == "MCE":
            return mix(predictions, locked)
        if model == "AA-MCE":
            return mix(predictions, aa_weights[index]) if patterns is None else aa_probability(predictions, patterns)
        return predictions[model]

    # reproduction check against the saved seed-averaged test predictions
    saved = pd.read_parquet(aa_root / "mean_test_predictions_all_conditions.parquet")
    columns = [f"score_{label}" for label in labels]
    reproduction = {}
    for model in ("MCE", "AA-MCE", "RAMT", "EvidFusion"):
        diffs = []
        for condition in CONDITIONS:
            regenerated = np.mean([probability(model, test_preds[s][condition], test_patterns[condition]) for s in seeds], axis=0)
            reference = saved.loc[(saved["model"] == model) & (saved["condition"] == condition), columns].to_numpy()
            diffs.append(float(np.abs(regenerated - reference).max()))
        reproduction[model] = max(diffs)

    # ---- offline selection timing (single CPU process) ----
    y_validation = target["validation"]
    candidates = {s: {i: {n: validation_preds[s][i][n] for n in components} for i in range(len(PATTERNS))} for s in seeds}
    tick = time.perf_counter()
    weights, _, _ = select_pattern_weights(candidates, eligible, y_validation, PATTERNS, pattern_labels, components, locked,
                                           float(settings["weight_step"]), float(settings["selection_margin"]))
    grid_seconds = time.perf_counter() - tick
    tick = time.perf_counter()
    thresholds = {s: {i: fast_thresholds(y_validation[eligible[i]], mix(candidates[s][i], weights["AA-MCE"][i])) for i in range(len(PATTERNS))} for s in seeds}
    threshold_seconds = time.perf_counter() - tick
    tick = time.perf_counter()
    for s in seeds:
        for i in range(len(PATTERNS)):
            fit_platt(y_validation[eligible[i]].astype(np.float64), mix(candidates[s][i], weights["AA-MCE"][i]))
    platt_seconds = time.perf_counter() - tick
    same_weights = all(abs(weights["AA-MCE"][i][n] - aa_weights[i][n]) < 1e-9 for i in range(len(PATTERNS)) for n in components)
    saved_thresholds = pd.read_csv(aa_root / "pattern_thresholds.csv")
    aa_saved = saved_thresholds.loc[saved_thresholds["variant"] == "AA-MCE"]
    threshold_gap = max(
        float(np.abs(aa_saved[(aa_saved["seed"] == s) & (aa_saved["pattern"] == pattern_labels[i])].set_index("label").loc[labels, "threshold"].to_numpy() - thresholds[s][i]).max())
        for s in seeds for i in range(len(PATTERNS))
    )
    timing = {
        "weight_grid_seconds": grid_seconds,
        "pattern_threshold_seconds": threshold_seconds,
        "pattern_platt_seconds": platt_seconds,
        "total_seconds": grid_seconds + threshold_seconds + platt_seconds,
        "selected_weights_equal_saved": bool(same_weights),
        "max_abs_threshold_difference_vs_saved": threshold_gap,
        "max_abs_prediction_difference_vs_saved": reproduction,
    }
    (output_root / "selection_timing.json").write_text(json.dumps(timing, indent=2), encoding="utf-8")

    # ---- threshold shift per pattern (saved validation-selected thresholds) ----
    rows = []
    for variant in ("MCE+AAT", "AA-MCE", "RAMT+AAT", "AttnFusion+AAT", "EvidFusion+AAT"):
        table = saved_thresholds.loc[saved_thresholds["variant"] == variant]
        by_pattern = {p: g.pivot(index="seed", columns="label", values="threshold")[labels].to_numpy().mean(axis=0) for p, g in table.groupby("pattern")}
        reference = by_pattern[pattern_labels[observed_index]]
        for label in pattern_labels:
            values = by_pattern[label]
            rows.append({"variant": variant, "pattern": label, "median": float(np.median(values)), "q1": float(np.quantile(values, 0.25)),
                         "q3": float(np.quantile(values, 0.75)), "labels_below_complete": int((values < reference - 1e-6).sum()),
                         "labels_above_complete": int((values > reference + 1e-6).sum())})
    pd.DataFrame(rows).to_csv(output_root / "threshold_shift_by_pattern.csv", index=False)

    # ---- validation probability per pattern: all / positive / negative entries ----
    positives = y_validation > 0.5
    rows = []
    for i, label in enumerate(pattern_labels):
        y = positives[eligible[i]]
        row = {"pattern": label, "validation_tracks": int(len(eligible[i])), "label_density": float(y.mean())}
        for model in ("MCE", "AA-MCE", "RAMT", "EvidFusion"):
            values = [probability(model, validation_preds[s][i], None, i) for s in seeds]
            row[f"{model}_mean"] = float(np.mean([v.mean() for v in values]))
            row[f"{model}_positive"] = float(np.mean([v[y].mean() for v in values]))
            row[f"{model}_negative"] = float(np.mean([v[~y].mean() for v in values]))
        rows.append(row)
    pd.DataFrame(rows).to_csv(output_root / "validation_probability_by_pattern.csv", index=False)

    # ---- decision-loss decomposition (per seed, then averaged) ----
    y_test = target["test"]
    lookup = {}
    for (variant, seed, pattern), group in saved_thresholds.groupby(["variant", "seed", "pattern"]):
        lookup[(variant, int(seed), pattern_labels.index(pattern))] = group.set_index("label").loc[labels, "threshold"].to_numpy()

    def per_track(variant: str, seed: int, patterns: np.ndarray) -> np.ndarray:
        out = np.empty((len(patterns), len(labels)), dtype=np.float32)
        for i in np.unique(patterns):
            out[patterns == i] = lookup[(variant, seed, int(i))][None, :]
        return out

    rows = []
    for model, global_variant, pattern_variant in VARIANT_PAIRS:
        for condition in CONDITIONS:
            values = []
            for s in seeds:
                p = probability(model, test_preds[s][condition], test_patterns[condition])
                f_global = f1_score(y_test, p >= lookup[(global_variant, s, observed_index)][None, :], average="macro", zero_division=0)
                f_pattern = f1_score(y_test, p >= per_track(pattern_variant, s, test_patterns[condition]), average="macro", zero_division=0)
                f_oracle = f1_score(y_test, p >= fast_thresholds(y_test, p)[None, :], average="macro", zero_division=0)
                values.append((f_global, f_pattern, f_oracle))
            f_global, f_pattern, f_oracle = np.mean(values, axis=0)
            rows.append({"model": model, "condition": condition, "global_thresholds": f_global, "pattern_thresholds": f_pattern,
                         "oracle_thresholds": f_oracle,
                         "share_recovered": (f_pattern - f_global) / (f_oracle - f_global) if f_oracle - f_global > 1e-9 else np.nan})
    pd.DataFrame(rows).to_csv(output_root / "decision_loss_decomposition.csv", index=False)

    # ---- complete condition: per-seed mAP on the natural-pattern subsets ----
    natural = test_patterns["observed"]
    rows = []
    for name, rows_mask in (("all", np.ones(len(y_test), bool)), ("audio+lyrics+visual", natural == observed_index),
                            ("audio+lyrics", natural == PATTERNS.index((1, 1, 0)))):
        y = y_test[rows_mask]
        keep = np.flatnonzero(y.sum(axis=0) > 0)
        scores = {"MCE": [], "AA-MCE": []}
        for s in seeds:
            predictions = test_preds[s]["observed"]
            for model in scores:
                p = probability(model, predictions, natural)[rows_mask]
                scores[model].append(float(np.mean([average_precision_score(y[:, label], p[:, label]) for label in keep])))
        rows.append({"subset": name, "tracks": int(rows_mask.sum()), "mAP_MCE": float(np.mean(scores["MCE"])),
                     "mAP_AA-MCE": float(np.mean(scores["AA-MCE"])),
                     "delta_per_seed": json.dumps([round(a - b, 5) for a, b in zip(scores["AA-MCE"], scores["MCE"])])})
    pd.DataFrame(rows).to_csv(output_root / "observed_subset_map.csv", index=False)

    completion = {"run_name": run_name, "elapsed_seconds": time.perf_counter() - started, "environment": environment_record(device)}
    (output_root / "completion.json").write_text(json.dumps(completion, indent=2), encoding="utf-8")
    return output_root


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--project-root", type=Path, default=Path("."))
    parser.add_argument("--config", default="configs/experiments.yaml")
    parser.add_argument("--run-name", default="decision_layer_diagnostics_v1")
    parser.add_argument("--output-root", type=Path, default=None,
                        help="where to write experiments/<run-name>/ (default: <project-root>/outputs)")
    args = parser.parse_args()
    project_root = args.project_root.resolve()
    config = load_config(project_root, args.config)
    output_base = args.output_root.resolve() if args.output_root else project_root / config["project"]["outputs_root"]
    print(run(project_root, output_base, config, args.run_name))


if __name__ == "__main__":
    main()
